// ─── Offers ─────────────────────────────────────────────────────────────

export const offers = (lang: TripLang = 'en'): Offer[] =>
  rawOffers(lang).map((o) => ({
    id: o.id,
    title: loc(o.title, lang),
    category: o.category,
    location: loc(o.location, lang),
    blurb: loc(o.blurb, lang),
    partner: o.partner,
    href: o.href,
    ...(o.flag ? { flag: o.flag } : {}),
  }));

export function getOffers(opts?: { category?: OfferCategory; flag?: OfferFlag; limit?: number; lang?: TripLang }): Offer[] {
  let out = offers(opts?.lang ?? 'en');
  if (opts?.category) out = out.filter((o) => o.category === opts.category);
  if (opts?.flag) out = out.filter((o) => o.flag === opts.flag);
  if (opts?.limit) out = out.slice(0, opts.limit);
  return out;
}

export function getEditorPicks(limit = 4, lang: TripLang = 'en'): Offer[] {
  return offers(lang).filter((o) => o.flag === 'editor-pick').slice(0, limit);
}

export function getLastMinute(limit = 6, lang: TripLang = 'en'): Offer[] {
  return offers(lang).filter((o) => o.flag === 'last-minute').slice(0, limit);
}

