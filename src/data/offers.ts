export type OfferCategory = 'hotels' | 'activities' | 'flights' | 'cars' | 'packages';
export type OfferFlag = 'last-minute' | 'end-of-season' | 'summer' | 'package' | 'editor-pick';
export type OfferPartner = 'lodging' | 'trip.com' | 'getyourguide' | 'economybookings';

/** A string translated into every supported site locale. */
export type Localized = Record<Lang, string>;

/** Raw offer record — visible text stored per-locale; resolved by offers(lang). */
interface RawOffer {
  id: string;
  title: Localized;
  category: OfferCategory;
  location: Localized;
  blurb: Localized;
  partner: OfferPartner;
  href: string;
  flag?: OfferFlag;
}

export interface Offer {
  id: string;
  title: string;
  category: OfferCategory;
  location: string;
  blurb: string;
  partner: OfferPartner;
  href: string;
  flag?: OfferFlag;
}

// ─── Helpers ────────────────────────────────────────────────────────────

function hotelsUrl(query: string, sid: string, lang: TripLang): string {
  return buildAffiliateHref({ partner: 'hotels', sid, destination: query, lang });
}

function carsUrl(pickupIATA: string, sid: string, lang: TripLang): string {
  return buildAffiliateHref({
    partner: 'cars',
    sid,
    query: { pickup_location: pickupIATA },
    lang,
  });
}

/** Resolve a Localized field to a single string, falling back to EN. */
function loc(field: Localized, lang: Lang): string {
  return field[lang] ?? field.en;
}

